#!/usr/bin/env python3
"""Build the same validated customer artwork catalog for LVGL and early boot."""
import argparse
import hashlib
from pathlib import Path
import struct
import zlib
from build_customer_boot_assets import export_source_images

ROOT = Path(__file__).resolve().parents[1]
IDS = {'background': 1, 'logo-large': 2, 'logo-small': 3,
       **{'hand-'+str(i): i+3 for i in range(1, 6)},
       'initialization': 9, 'system': 10, 'ready-large': 11,
       'version-2.0': 12, 'powered-by-mechatro': 13}


def customer_payload(root=ROOT):
    images, pixels = export_source_images(root)
    start = 32 + 64 * len(images)
    entries, pieces, cursor = [], [], start
    for image in images:
        ident = image.get('asset_id', IDS.get(image['id']))
        if not ident or not 1 <= ident <= 13:
            raise ValueError('unknown customer asset: '+image['id'])
        tag = image.get('tag', image.get('locale', 'en')) if 9 <= ident <= 12 else ''
        if tag == '*':
            tag = 'en'
        if len(tag.encode('ascii')) >= 16:
            raise ValueError('invalid customer language tag')
        x, y = 0, 0
        if 'source_bbox_xywh' in image:
            x, y = image['source_bbox_xywh'][:2]
            y += 8
        elif image['role'] == 'gesture':
            x = image['source_bbox_xyxy'][0] - image['reference_bbox_xyxy'][0]
            y = image['source_bbox_xyxy'][1] - image['reference_bbox_xyxy'][1] + 8
        w, h = image['width'], image['height']
        if not (0 <= x <= 1280-w and 0 <= y <= 400-h):
            raise ValueError('customer artwork outside display: '+image['id'])
        fmt = 1 if image['format'] == 'BGRA8888' else 2
        r, g, b = image.get('color_rgb', [255, 255, 255])
        piece = pixels[image['offset']:image['offset']+image['bytes']]
        entries.append(struct.pack('<6I2i2I16s2I', ident, fmt, w, h,
                                   cursor, len(piece), x, y, r<<16 | g<<8 | b,
                                   0, tag.encode('ascii'), 0, 0))
        pieces.append(piece)
        cursor += len(piece)
    raw = b'UNBCAT1\0' + struct.pack('<6I', cursor, len(images), 64, start, 0, 0)
    raw += b''.join(entries) + b''.join(pieces)
    if len(raw) > 8*1024*1024 or len(zlib.compress(raw, 9)) > 2*1024*1024:
        raise ValueError('customer art exceeds existing boot resource budget')
    return raw


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    raw = customer_payload(args.root)
    data = zlib.compress(raw, 9)
    destination = args.output or args.root/'aic_ui/generated_assets/customer_boot/boot_customer_blob.c'
    destination.parent.mkdir(parents=True, exist_ok=True)
    lines = [', '.join('0x%02x' % v for v in data[i:i+20]) for i in range(0, len(data), 20)]
    content = ('/* Generated by tools/build_customer_boot_pack.py; do not edit. */\n'
               '#include <stddef.h>\nconst unsigned char boot_customer_blob[] = {\n' +
               ',\n'.join(lines) + '\n};\n' +
               'const size_t boot_customer_blob_size = sizeof(boot_customer_blob);\n' +
               'const size_t boot_customer_blob_raw_size = %dU;\n' % len(raw))
    if not destination.exists() or destination.read_text() != content:
        destination.write_text(content)
    print('customer art raw=%d compressed=%d sha256=%s' %
          (len(raw), len(data), hashlib.sha256(raw).hexdigest()))


if __name__ == '__main__':
    main()
