#!/usr/bin/env python3
"""Offline welcome artwork. Pillow 10.4 + RAQM, fonttools 4.55.3.

Only whole-word 4bpp glyphs ship; the original licensed fonts are build inputs.
Native early boot and LVGL consume the exact same quantized pixels.
"""
from pathlib import Path
import json, re, hashlib
from PIL import Image, ImageDraw, ImageFont, features
from fontTools.ttLib import TTFont

ROOT=Path(__file__).resolve().parents[1]
FONTS=ROOT/'tools/boot_handwriting_fonts'
assert features.check('raqm'), 'RAQM is required: do not render disconnected Arabic'
registry=json.loads((ROOT/'i18n/locales.json').read_text())
catalog={}
for p in sorted((ROOT/'i18n/locales').glob('*.json'))+sorted((ROOT/'i18n/fragments').glob('*.json')):
    data=json.loads(p.read_text())
    for tag,entries in data.items():
        if isinstance(entries,dict) and 'Welcome' in entries:catalog[tag]=entries['Welcome']
choices={
 'en':('aic_ui/font/OoohBaby-Regular.ttf',4),
 'zh-Hans':('tools/boot_handwriting_fonts/MaShanZheng-Regular.ttf',0),
 'ko':('tools/boot_handwriting_fonts/NanumPenScript-Regular.ttf',0),
 'ja':('tools/boot_handwriting_fonts/Yomogi-Regular.ttf',5),
 'ar':('tools/boot_handwriting_fonts/ArefRuqaa-Regular.ttf',0),
 'ru':('tools/boot_handwriting_fonts/Caveat[wght].ttf',1),
}
for t in ['tr','fr','pl','de']: choices[t]=choices['en']
locales=[r for r in registry if r['enabled'] and r['translations_ready']]
assert set(choices)=={r['tag'] for r in locales}, 'New released locale needs welcome font review'
out=ROOT/'tools/boot_handwriting_preview';out.mkdir(exist_ok=True)
variants={False:[],True:[]}; report=[]
for i,loc in enumerate(locales):
    tag=loc['tag'];text=catalog[tag];path,stroke=choices[tag];path=ROOT/path
    coverage=TTFont(path).getBestCmap()
    assert all(ord(c) in coverage for c in text), (tag,'missing glyph',text)
    font=ImageFont.truetype(str(path),560,layout_engine=ImageFont.Layout.RAQM)
    kw={'direction':'rtl' if tag=='ar' else 'ltr','language':tag.split('-')[0]}
    box=font.getbbox(text,stroke_width=stroke,**kw)
    im=Image.new('L',(box[2]-box[0]+16,box[3]-box[1]+16))
    ImageDraw.Draw(im).text((8-box[0],8-box[1]),text,font=font,fill=255,stroke_width=stroke,**kw)
    for compact in [False,True]:
        if tag=='en':
            # Preserve the approved quantized English pixels across Pillow /
            # shaping-library versions, rather than re-typesetting the brand.
            assert text=='Welcome', 'A new English word needs reviewed artwork'
            mask=Image.open(FONTS/('approved-welcome'+('_compact' if compact else '')+'.png')).convert('L')
            y=0
        else:
            mask=im.crop(im.getbbox());maxh=76 if compact else 94
            maxw=430 if compact else 480
            mask.thumbnail((maxw,maxh),Image.Resampling.LANCZOS)
            y=max(0,round(((92 if compact else 112)-mask.height)/2))
        w,h=mask.size; vals=[min(15,(v+8)//17) for v in mask.tobytes()]
        data=bytes((vals[j]<<4)|(vals[j+1] if j+1<len(vals) else 0) for j in range(0,len(vals),2))
        variants[compact].append((w,h,y,data))
        if compact:
            preview=Image.new('RGB',(500,128),(234,240,246));alpha=Image.frombytes('L',(w,h),bytes(v*17 for v in vals));preview.paste((82,109,130),((500-w)//2,y,(500+w)//2,y+h),alpha)
            preview.save(out/(tag+'.png'))
            report.append({'tag':tag,'text':text,'font':path.name,'font_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'width':w,'height':h,'y':y,'bytes':len(data)})

def byte_lines(data):return '\n'.join('    '+','.join(f'0x{x:02x}' for x in data[i:i+24])+',' for i in range(0,len(data),24))
for compact,arts in variants.items():
    name='lv_font_boot_welcome'+('_compact' if compact else '')
    rows=['    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},']
    data=b''
    for w,h,y,bits in arts:
        rows.append('    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = 0, .ofs_y = %d},'%(len(data),w*16,w,h,128-h-y));data+=bits
    source='''/* Generated by tools/gen_boot_handwriting.py. Whole pre-shaped words.
 * Font provenance and OFL licenses: tools/boot_handwriting_fonts/sources.json. */
#include "un260/lv_core/boot_anim/boot_theme_config.h"
#if UI_BOOT_ANIM_THEME %s UI_BOOT_ANIM_THEME_D
#include "lvgl/lvgl.h"
static const uint8_t glyph_bitmap[] = {
%s
};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {
%s
};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    .range_start = 57344, .range_length = %d, .glyph_id_start = 1,
    .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
    .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY
}};
static lv_font_fmt_txt_glyph_cache_t cache;
static lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,
    .kern_classes = 0, .bitmap_format = 0, .cache = &cache
};
const lv_font_t %s = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 128, .base_line = 0, .dsc = &font_dsc
};
#endif
'''%('==' if compact else '!=',byte_lines(data),'\n'.join(rows),len(arts),name)
    (ROOT/f'un260/font/{name}.c').write_text(source)

native='''/* Generated from the same quantized word pixels as the LVGL glyphs. */
#ifndef BOOT_WELCOME_NATIVE_H
#define BOOT_WELCOME_NATIVE_H
#include <stdint.h>
#include <string.h>
#include "un260/lv_core/boot_anim/boot_theme_config.h"
'''
for compact,arts in variants.items():
    native+='#if UI_BOOT_ANIM_THEME %s UI_BOOT_ANIM_THEME_D\n'%('==' if compact else '!=')
    data=b'';rows=[]
    for w,h,y,bits in arts:rows.append('{%d,%d,%d,%d}'%(len(data),w,h,y));data+=bits
    native+='static const uint8_t boot_welcome_pixels[]={\n'+byte_lines(data)+'\n};\n'
    native+='static const struct {uint32_t offset;uint16_t w,h,y;} boot_welcome_art[]={'+','.join(rows)+'};\n#endif\n'
native+='''static inline void boot_welcome_native_apply(uint8_t *dst,unsigned index)
{
    if(index>=sizeof(boot_welcome_art)/sizeof(boot_welcome_art[0]))index=0;
    memset(dst,0,500U*128U*4U);
    unsigned w=boot_welcome_art[index].w,h=boot_welcome_art[index].h;
    const uint8_t *src=boot_welcome_pixels+boot_welcome_art[index].offset;
    for(unsigned y=0;y<h;++y)for(unsigned x=0;x<w;++x){
        unsigned n=y*w+x;
        uint8_t a=((n&1)?src[n/2]&15:src[n/2]>>4)*17;
        uint8_t *p=dst+((y+boot_welcome_art[index].y)*500U+(500U-w)/2+x)*4U;
#if UI_BOOT_ANIM_THEME == UI_BOOT_ANIM_THEME_D
        p[0]=130;p[1]=109;p[2]=82;
#else
        p[0]=245;p[1]=244;p[2]=242;
#endif
        p[3]=a;
    }
}
#endif
'''
(ROOT/'un260/font/boot_welcome_native.h').write_text(native)
header='#ifndef BOOT_WELCOME_REGISTRY_H\n#define BOOT_WELCOME_REGISTRY_H\n#define BOOT_WELCOME_COUNT %dU\n'%len(locales)
header+='static const char *const boot_welcome_tags[]={'+','.join(json.dumps(r['tag']) for r in locales)+'};\n'
header+='static const unsigned boot_welcome_ids[]={'+','.join(str(r['id']) for r in locales)+'};\n'
header+='static const char *const boot_welcome_texts[]={'+','.join('"'+''.join('\\x%02x'%b for b in chr(0xe000+i).encode())+'"' for i in range(len(locales)))+'};\n#endif\n'
(ROOT/'un260/lv_core/boot_anim/boot_welcome_registry.h').write_text(header)
(out/'metrics.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(report,ensure_ascii=False,indent=2))

manifest={'locales':report,'outputs':{},'generator_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
for filename in ['un260/font/lv_font_boot_welcome.c','un260/font/lv_font_boot_welcome_compact.c','un260/font/boot_welcome_native.h','un260/lv_core/boot_anim/boot_welcome_registry.h']:
    manifest['outputs'][filename]=hashlib.sha256((ROOT/filename).read_bytes()).hexdigest()
(ROOT/'un260/font/boot_handwriting_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
