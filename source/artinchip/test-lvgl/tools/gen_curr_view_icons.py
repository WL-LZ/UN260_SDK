#!/usr/bin/env python3
"""Generate page-private Currency view icons from saved Lucide PNGs (Pillow)."""
import argparse
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools/icon_sources/currency_view"
TARGET = ROOT / "un260/lv_core/page_07_curr/page_07_curr_view_icons.h"
ICONS = (
    ("curr_view_grid_icon", "mode-grid.png", 16, (81, 104, 121)),
    ("curr_view_card_icon", "mode-card.png", 18, (81, 104, 121)),
    ("curr_view_star_outline", "star-off.png", 16, (152, 168, 180)),
    ("curr_view_star_filled", "star-on.png", 16, (24, 91, 194)),
)


def generate():
    lines = [
        "/* Generated by tools/gen_curr_view_icons.py; do not edit by hand.",
        " * Lucide 1.8.0 artwork, ISC license; source and full license:",
        " * tools/icon_sources/currency_view/", " */",
        "#ifndef PAGE07_CURR_VIEW_ICONS_H",
        "#define PAGE07_CURR_VIEW_ICONS_H",
    ]
    for symbol, filename, size, rgb in ICONS:
        with Image.open(SOURCE / filename) as source:
            if source.size != (66, 66):
                raise ValueError("Expected 66x66 source: " + filename)
            alpha = source.convert("RGBA").getchannel("A")
            alpha = alpha.resize((size, size), getattr(Image, "Resampling", Image).LANCZOS)
        # LVGL indexed-8 palette entries use BGRA. The index is coverage,
        # preserving antialiasing while keeping the requested RGB exact.
        palette = b"".join(bytes((rgb[2], rgb[1], rgb[0], a)) for a in range(256))
        data = palette + alpha.tobytes()
        lines += [
            "static const uint8_t " + symbol + "_pixels[] = {",
            "\n".join(",".join(str(b) for b in data[i:i + 24]) + ","
                      for i in range(0, len(data), 24)),
            "};", "static const lv_img_dsc_t " + symbol + " = {",
            " .header={.cf=LV_IMG_CF_INDEXED_8BIT,.w=" + str(size) + ",.h=" + str(size) + "},",
            " .data_size=sizeof(" + symbol + "_pixels),.data=" + symbol + "_pixels", "};",
        ]
    return "\n".join(lines + ["#endif", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=TARGET,
                        help="output header; defaults to the Currency private resource header")
    args = parser.parse_args()
    args.output.write_text(generate(), encoding="utf-8")
    print("Generated " + str(args.output))


if __name__ == "__main__":
    main()
