#!/usr/bin/env python3
"""Validate candidate glyph files and stage only runtime assets plus checksum index.
Does not enable a locale or assert layout acceptance.
"""
import argparse,hashlib,json,shutil,zlib,unicodedata
import gen_i18n
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('candidate',type=Path,nargs='?')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    output=ROOT/'aic_ui/lvgl_data/locale_fonts'
    source_root=args.candidate or output
    if not args.check and args.candidate is None: parser.error('candidate is required when staging assets')
    manifest=json.loads((source_root/'manifest.json').read_text())
    registry,catalogues=gen_i18n.catalogues()
    contracts=gen_i18n.read_json(gen_i18n.I18N/'font_contracts.json')['large_text']
    sizes=manifest['sizes']
    assert sizes and len(sizes)==len(set(sizes))
    records=[];content=['/* Generated by prepare_locale_font_assets.py. */',
        '#define UN260_LOCALE_FONT_SIZE_COUNT %d'%len(sizes)]
    banks=[]
    for entry in registry:
        if entry['id']==0: continue
        tag=entry['tag']
        banks.append('    { .language=(language_t)%d, .assets=assets_%s, .count=UN260_LOCALE_FONT_SIZE_COUNT }' % (entry['id'],tag.replace('-','_')))
        locale=manifest['locales'][tag]
        assert locale['missing_translation_count']==0,tag
        texts=[item['name'] for item in registry if item['tag']==tag]
        for value in catalogues[tag].values():
            texts.extend(value.values() if isinstance(value,dict) else [value])
        required={ord(c) for text in texts for c in text if ord(c)>=128 and unicodedata.category(c)!='Cf'}
        missing=required-set(locale['codepoints'])
        assert not missing,(tag,'missing font glyphs',sorted(missing))
        assert [f['size'] for f in locale['files']]==sizes,tag
        content.append('static const struct font_asset assets_%s[] = {'%tag.replace('-','_'))
        for item in locale['files']:
            keys=contracts.get(str(item['size']))
            assert item.get('text_keys')==keys,(tag,item['size'],'font contract changed')
            size_texts=[]
            for value in ([catalogues[tag][key] for key in keys] if keys else texts):
                size_texts.extend(value.values() if isinstance(value,dict) else [value])
            size_required={ord(c) for text in size_texts for c in text if ord(c)>=128 and unicodedata.category(c)!='Cf'}
            assert size_required<=set(item.get('codepoints',locale['codepoints'])),(tag,item['size'],'missing size-specific glyph')
            name='font-%d.bin'%item['size'];assert name==item['file']
            path=source_root/tag/name;data=path.read_bytes()
            assert len(data)==item['bytes'] and hashlib.sha256(data).hexdigest()==item['sha256'],path
            content.append('    {%d, %du, 0x%08Xu, "%s/%s"},'%(item['size'],len(data),zlib.crc32(data),tag,name))
            records.append((path,output/tag/name))
        content.append('};')
    content.append('#define UN260_LOCALE_BANKS { \\\n' + ', \\\n'.join(banks) + ' \\\n}')
    index=ROOT/'un260/font/ui_locale_font_assets.inc'
    generated='\n'.join(content)+'\n'
    if args.check:
        assert index.read_text()==generated,'Font index differs from staged assets'
        print('Locale font assets PASS: file hashes, byte counts, index and current catalogue glyph coverage')
        return
    # No destination mutation until all source files pass validation.
    for source,destination in records:
        destination.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,destination)
    index.write_text(generated)
    (output/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    print('Verified locale assets:',len(records),'files,',sum(p.stat().st_size for p,_ in records),'bytes')
if __name__=='__main__':main()
